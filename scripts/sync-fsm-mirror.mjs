#!/usr/bin/env node
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { fileURLToPath } from 'node:url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const serviceRoot = path.resolve(__dirname, '..');
const mowerRoot = path.resolve(process.env.MOWER_REPO || path.join(serviceRoot, '..', 'pudu_ratel_app_mower'));
const mirrorRoot = path.join(serviceRoot, 'src', 'sim', 'fsm-mirror');

const mirrorFiles = [
  ['src/domain/shared/TaskFSM.ts', 'domain/shared/TaskFSM.ts'],
  ['src/domain/shared/LoggerLike.ts', 'domain/shared/LoggerLike.ts'],
  ['src/domain/mapping/MappingSession.ts', 'domain/mapping/MappingSession.ts'],
  ['src/domain/mowing/MowingTask.ts', 'domain/mowing/MowingTask.ts'],
  ['src/domain/mapEdit/MapEditSession.ts', 'domain/mapEdit/MapEditSession.ts'],
  ['src/features/shared/mapping/BackendStatusMapper.ts', 'features/shared/mapping/BackendStatusMapper.ts'],
  ['src/features/shared/mapping/BackendPhaseMapper.ts', 'features/shared/mapping/BackendPhaseMapper.ts'],
  ['src/features/shared/mapping/unknownBackendSubStatus.ts', 'features/shared/mapping/unknownBackendSubStatus.ts'],
  ['src/features/shared/mapping/cloudWorkStatus.ts', 'features/shared/mapping/cloudWorkStatus.ts'],
  ['src/features/mapping/state/mappingBackendRegistry.ts', 'features/mapping/state/mappingBackendRegistry.ts'],
  ['src/features/mowing/state/mowingBackendRegistry.ts', 'features/mowing/state/mowingBackendRegistry.ts'],
  ['src/infra/events/Arbitrator.ts', 'services/events/Arbitrator.ts'],
  ['src/infra/events/EventAdapter.ts', 'services/events/EventAdapter.ts'],
  ['src/features/shared/mapping/TaskEventPipeline.ts', 'features/shared/mapping/TaskEventPipeline.ts'],
];

function sha256(text) {
  return crypto.createHash('sha256').update(text).digest('hex');
}

function toPosix(value) {
  return value.split(path.sep).join('/');
}

function relativeImport(fromFileAbs, targetAbsNoExt) {
  let rel = toPosix(path.relative(path.dirname(fromFileAbs), targetAbsNoExt));
  if (!rel.startsWith('.')) rel = `./${rel}`;
  return rel;
}

function rewriteAliases(content, destAbs) {
  return content.replace(/from\s+(['"])@\/([^'"]+)\1/g, (_match, quote, aliasPath) => {
    const targetAbs = path.join(mirrorRoot, aliasPath);
    return `from ${quote}${relativeImport(destAbs, targetAbs)}${quote}`;
  });
}

function ensureDir(filePath) {
  fs.mkdirSync(path.dirname(filePath), { recursive: true });
}

if (!fs.existsSync(mowerRoot)) {
  console.error(`mower repo not found: ${mowerRoot}`);
  process.exit(1);
}

const syncedAt = new Date().toISOString();
const manifest = {
  mowerRoot,
  mirrorRoot,
  syncedAt,
  files: [],
};

for (const [sourceRel, destRel] of mirrorFiles) {
  const sourceAbs = path.join(mowerRoot, sourceRel);
  const destAbs = path.join(mirrorRoot, destRel);
  if (!fs.existsSync(sourceAbs)) {
    console.warn(`skip missing source: ${sourceAbs}`);
    continue;
  }
  const source = fs.readFileSync(sourceAbs, 'utf8');
  const hash = sha256(source);
  const rewritten = rewriteAliases(source, destAbs);
  const header = [
    '/* eslint-disable */',
    '// @ts-nocheck',
    `// !!! AUTO-GENERATED FROM mower/${sourceRel}. DO NOT EDIT. !!!`,
    `// Source SHA-256: ${hash}`,
    `// Synced at: ${syncedAt}`,
    '',
  ].join('\n');
  ensureDir(destAbs);
  fs.writeFileSync(destAbs, header + rewritten, 'utf8');
  manifest.files.push({ source: sourceRel, dest: toPosix(path.relative(serviceRoot, destAbs)), sha256: hash });
}

const shimPath = path.join(mirrorRoot, 'domain/shared/AppError.ts');
ensureDir(shimPath);
fs.writeFileSync(
  shimPath,
  [
    '/* eslint-disable */',
    '// !!! LOCAL TYPE SHIM FOR MIRRORED MowingTask.ts. DO NOT IMPORT FROM SIMULATOR CODE. !!!',
    '// The source mirror list intentionally does not copy mower/domain/shared/AppError.ts.',
    '',
    'export interface AppError {',
    '  readonly code: string;',
    '  readonly message?: string;',
    '  readonly kind?: string;',
    '  readonly recoverable?: boolean;',
    '}',
    '',
  ].join('\n'),
  'utf8',
);

const readmePath = path.join(mirrorRoot, 'README.SYNC.md');
ensureDir(readmePath);
fs.writeFileSync(
  readmePath,
  [
    '# FSM mirror sync',
    '',
    'This directory is generated by `npm run sync-fsm-mirror`.',
    '',
    '- Do not edit mirrored files manually.',
    '- Make FSM changes in the mower repository first.',
    '- After syncing, run `npm run build && npm test` and fix simulator adapter errors under `src/sim/`.',
    '',
  ].join('\n'),
  'utf8',
);

fs.writeFileSync(path.join(mirrorRoot, '.manifest.json'), `${JSON.stringify(manifest, null, 2)}\n`, 'utf8');
console.log(`Synced ${mirrorFiles.length} FSM mirror files from ${mowerRoot}`);
